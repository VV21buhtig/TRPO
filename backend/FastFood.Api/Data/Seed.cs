    /// <summary>
    /// EnsureCreated не добавляет новые таблицы в уже существующую БД.
    /// Создаём журнал статусов отдельно, чтобы обновление не требовало удаления данных.
    /// </summary>
    private static async Task EnsureStatusHistoryTableAsync(AppDbContext db)
    {
        if (db.Database.IsSqlite())
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "OrderStatusHistories" (
                    "Id" INTEGER NOT NULL CONSTRAINT "PK_OrderStatusHistories" PRIMARY KEY AUTOINCREMENT,
                    "OrderId" INTEGER NOT NULL,
                    "Status" TEXT NOT NULL,
                    "ChangedByUserId" INTEGER NULL,
                    "ChangedByName" TEXT NOT NULL,
                    "ChangedByRole" TEXT NOT NULL,
                    "ChangedAt" TEXT NOT NULL,
                    "Comment" TEXT NULL,
                    CONSTRAINT "FK_OrderStatusHistories_Orders_OrderId"
                        FOREIGN KEY ("OrderId") REFERENCES "Orders" ("Id") ON DELETE CASCADE,
                    CONSTRAINT "FK_OrderStatusHistories_Users_ChangedByUserId"
                        FOREIGN KEY ("ChangedByUserId") REFERENCES "Users" ("Id") ON DELETE SET NULL
                );
                """);
            await db.Database.ExecuteSqlRawAsync("""
                CREATE INDEX IF NOT EXISTS "IX_OrderStatusHistories_OrderId_ChangedAt"
                    ON "OrderStatusHistories" ("OrderId", "ChangedAt");
                """);
        }
        else
        {
            await db.Database.ExecuteSqlRawAsync("""
                CREATE TABLE IF NOT EXISTS "OrderStatusHistories" (
                    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    "OrderId" integer NOT NULL REFERENCES "Orders" ("Id") ON DELETE CASCADE,
                    "Status" text NOT NULL,
                    "ChangedByUserId" integer NULL REFERENCES "Users" ("Id") ON DELETE SET NULL,
                    "ChangedByName" text NOT NULL,
                    "ChangedByRole" text NOT NULL,
                    "ChangedAt" timestamp with time zone NOT NULL,
                    "Comment" text NULL
                );
                """);
            await db.Database.ExecuteSqlRawAsync("""
                CREATE INDEX IF NOT EXISTS "IX_OrderStatusHistories_OrderId_ChangedAt"
                    ON "OrderStatusHistories" ("OrderId", "ChangedAt");
                """);
        }
    }

    /// <summary>
    /// Добавляем признак активности сотрудника в уже существующую БД.
    /// Физическое удаление пользователей не используется: доступ только блокируется.
    /// </summary>
    private static async Task EnsureUserActiveColumnAsync(AppDbContext db)
    {
        if (db.Database.IsSqlite())
        {
            var hasColumn = await db.Database
                .SqlQueryRaw<int>("""
                    SELECT COUNT(*) AS "Value"
                    FROM pragma_table_info('Users')
                    WHERE name = 'IsActive'
                    """)
                .SingleAsync();
            if (hasColumn == 0)
            {
                await db.Database.ExecuteSqlRawAsync(
                    """ALTER TABLE "Users" ADD COLUMN "IsActive" INTEGER NOT NULL DEFAULT 1;""");
            }
        }
        else
        {
            await db.Database.ExecuteSqlRawAsync(
                """ALTER TABLE "Users" ADD COLUMN IF NOT EXISTS "IsActive" boolean NOT NULL DEFAULT TRUE;""");
        }
    }

    /// <summary>
    /// Привязка акции к блюду/категории появилась позже. Для существующей БД
    /// добавляем колонки без пересоздания таблицы; старые акции остаются
    /// информационными (Scope = None), пока менеджер не выберет цель.
    /// </summary>
    private static async Task EnsurePromotionColumnsAsync(AppDbContext db)
    {
        if (db.Database.IsSqlite())
        {
            var columns = await db.Database
                .SqlQueryRaw<string>("""
                    SELECT name AS "Value" FROM pragma_table_info('Promotions')
                    """)
                .ToListAsync();
            if (!columns.Contains("Scope"))
            {
                await db.Database.ExecuteSqlRawAsync(
                    """ALTER TABLE "Promotions" ADD COLUMN "Scope" TEXT NOT NULL DEFAULT 'None';""");
            }
            if (!columns.Contains("Category"))
            {
                await db.Database.ExecuteSqlRawAsync(
                    """ALTER TABLE "Promotions" ADD COLUMN "Category" TEXT NULL;""");
            }
            if (!columns.Contains("MenuItemId"))
            {
                await db.Database.ExecuteSqlRawAsync(
                    """ALTER TABLE "Promotions" ADD COLUMN "MenuItemId" INTEGER NULL;""");
            }
        }
        else
        {
            await db.Database.ExecuteSqlRawAsync(
                """ALTER TABLE "Promotions" ADD COLUMN IF NOT EXISTS "Scope" text NOT NULL DEFAULT 'None';""");
            await db.Database.ExecuteSqlRawAsync(
                """ALTER TABLE "Promotions" ADD COLUMN IF NOT EXISTS "Category" text NULL;""");
            await db.Database.ExecuteSqlRawAsync(
                """ALTER TABLE "Promotions" ADD COLUMN IF NOT EXISTS "MenuItemId" integer NULL;""");
        }
    }

    /// <summary>
    /// Для заказов, созданных до появления журнала, сохраняем исходную запись,
    /// чтобы история не начиналась с пустого места.
    /// </summary>
    private static async Task BackfillStatusHistoryAsync(AppDbContext db)
    {
        var orderIds = await db.Orders
            .Where(o => !db.OrderStatusHistories.Any(h => h.OrderId == o.Id))
            .Select(o => o.Id)
            .ToListAsync();

        if (orderIds.Count == 0)
        {
            return;
        }

        var orders = await db.Orders
            .Where(o => orderIds.Contains(o.Id))
            .ToListAsync();
        var userIds = orders
            .Select(o => o.OperatorId ?? o.CustomerId)
            .Where(id => id.HasValue)
            .Select(id => id!.Value)
            .Distinct()
            .ToList();
        var users = await db.Users
            .Where(u => userIds.Contains(u.Id))
            .ToDictionaryAsync(u => u.Id);

        foreach (var order in orders)
        {
            var actorId = order.OperatorId ?? order.CustomerId;
            var actor = actorId.HasValue && users.TryGetValue(actorId.Value, out var found)
                ? found
                : null;
            db.OrderStatusHistories.Add(new OrderStatusHistory
            {
                OrderId = order.Id,
                Status = order.Status,
                ChangedByUserId = actor?.Id,
                ChangedByName = actor?.Name ?? "Система",
                ChangedByRole = actor?.Role ?? "System",
                ChangedAt = order.CreatedAt,
                Comment = "Запись создана при миграции журнала",
            });
        }

        await db.SaveChangesAsync();
    }
}
